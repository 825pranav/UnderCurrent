#!/usr/bin/env python3
"""
gen_bundle_config.py — build a minimal OCI config.json for a hand-driven
bare-runc container, using the image's own Entrypoint/Cmd/Env/WorkingDir
(read via `podman inspect` on the image) merged onto a baseline generated by
`runc spec`. Host networking (no network namespace) — this experiment only
needs the process to run and be checkpoint/restored, not real connectivity.

Usage: gen_bundle_config.py <image> <rootfs_path> <hostname> <out_config_json> [EXTRA_ENV=val ...]
"""
import json
import subprocess
import sys


def podman_inspect_image(image):
    r = subprocess.run(
        ["podman", "inspect", image], capture_output=True, text=True, check=True
    )
    return json.loads(r.stdout)[0]


def main():
    image, rootfs, hostname, out_path = sys.argv[1:5]
    extra_env = sys.argv[5:]

    info = podman_inspect_image(image)
    cfg = info.get("Config", {}) or info.get("config", {})
    entrypoint = cfg.get("Entrypoint") or []
    cmd = cfg.get("Cmd") or []
    args = entrypoint + cmd
    if not args:
        raise SystemExit(f"no Entrypoint/Cmd found for image {image}")

    env = list(cfg.get("Env") or [])
    env.extend(extra_env)
    workdir = cfg.get("WorkingDir") or "/"

    # Baseline from `runc spec` (standard mounts: proc, dev, sys, devpts,
    # mqueue, shm — this is exactly what fix1b was missing once conmon tore
    # things down; a fresh runc spec always sets these up correctly).
    r = subprocess.run(["runc", "spec", "--rootless=false"], cwd="/tmp",
                        capture_output=True, text=True)
    baseline = json.loads(open("/tmp/config.json").read())

    baseline["root"]["path"] = rootfs
    baseline["root"]["readonly"] = False
    baseline["hostname"] = hostname
    baseline["process"]["terminal"] = False
    baseline["process"]["args"] = args
    baseline["process"]["cwd"] = workdir
    baseline["process"]["env"] = env

    # Host networking: drop the network namespace entry entirely (if any),
    # so we don't need to pre-create/manage a netns ourselves.
    baseline["linux"]["namespaces"] = [
        ns for ns in baseline["linux"]["namespaces"] if ns.get("type") != "network"
    ]

    with open(out_path, "w") as f:
        json.dump(baseline, f, indent=2)
    print(f"wrote {out_path}")
    print(f"args: {args}")
    print(f"env: {env}")


if __name__ == "__main__":
    main()
