# shared/cross_eval.py — Cross-Controller Evaluation Harness
#
# Runs both the stateless (S) and stateful (F) controllers on domain-appropriate
# fault scenarios and computes the same 6 research metrics for both.
#
# WHY FAULT SCENARIOS DIFFER BY DESIGN
# ──────────────────────────────────────
# The two controllers handle different kernel signal domains:
#   Stateless: process_exit, tcp_connect
#   Stateful : blk_io_latency, vfs_write_error, vfs_read_error, volume_mount_lost
#
# Cross-controller comparison is therefore organised by *severity level*, not
# by identical fault type.  Both controllers are exercised at four severity levels:
#
#   Level 0 — sub-threshold  : fault present but score below lowest threshold
#                              → expected: no_action
#   Level 1 — minor          : score crosses lowest threshold
#                              → expected: minor remediation (restart / flush_io_queue)
#   Level 2 — major          : score crosses repair/reschedule threshold
#                              → expected: major remediation (reschedule / checkpoint+restart)
#   Level 3 — critical       : maximum score
#                              → expected: escalation (reschedule / escalate)
#   Level R — recovery       : same scenario as Level 1, then events cleared
#                              → measures MTTR from fault to first no_action
#
# METRICS COMPUTED (same set as shared/metrics.py)
# ──────────────────────────────────────────────────
#   decision_accuracy      — fraction of scenarios where action matches expected
#   reversibility_ratio    — fraction of non-no_action decisions that are reversible
#   explanation_completeness — fraction of decisions with all required trace fields
#   unsafe_action_suppression_rate — fraction of decisions blocked by safety gate
#   mttr_seconds           — seconds from fault injection to recovery (Level R only)
#   divergence_rate        — fraction of real decisions that diverge from shadow
#
# Data source: no pre-existing trace files.  All results are generated by
#              running actual controller code in-process via importlib.
# Results out: shared/cross_eval_results.json
#
# Usage (from repo root):
#   python3 shared/cross_eval.py

