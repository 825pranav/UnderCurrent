# ── Required fields for explanation completeness (mirrors shared/metrics.py) ──
_REQUIRED_FIELDS = ("why", "action", "score", "kernel_signals", "dag_pattern")


def _complete(trace: dict) -> bool:
    for field in _REQUIRED_FIELDS:
        val = trace.get(field)
        if val is None:
            return False
        if isinstance(val, str) and val == "":
            return False
        if isinstance(val, list) and len(val) == 0 and trace.get("action") != "no_action":
            return False
    return True


# ── Stateless runner ───────────────────────────────────────────────────────────

def _run_sl_scenario(mods: dict, scenario: dict, now: float) -> dict:
    """Run one stateless scenario. Returns a result dict."""
    StateStore = mods["state_store"].StateStore
    reconcile  = mods["reconcile"].reconcile
    execute    = mods["actions"].execute

    if scenario.get("level") == "R":
        # Two-cycle measurement for MTTR
        store_fault = StateStore(window_seconds=60)
        for ev in scenario["fault_events"]:
            store_fault.record({"container": _CONTAINER, "pid": 1,
                                "time": now, **ev})
        fault_decisions = reconcile(store_fault, shadow=False)
        fault_t = time.time()
        fault_dec = next((d for d in fault_decisions if d["container"] == _CONTAINER), None)
        fault_result = execute(fault_dec) if fault_dec else {}

        # Clear window: inject recovery events with timestamps 70s in the past
        store_recovery = StateStore(window_seconds=60)
        for ev in scenario.get("recovery_events", []):
            store_recovery.record({"container": _CONTAINER, "pid": 1,
                                   "time": now - 70, **ev})
        recovery_decisions = reconcile(store_recovery, shadow=False)
        recovery_t = time.time()
        recovery_dec = next((d for d in recovery_decisions if d["container"] == _CONTAINER), None)
        if not recovery_dec:
            # Empty store → no decision generated; treat as no_action
            recovery_dec = {"container": _CONTAINER, "action": "no_action",
                            "score": 0.0, "reason": "no events in window",
                            "kernel_signals": [], "dag_pattern": "nominal",
                            "mode": "real", "timestamp": recovery_t}
        recovery_result = execute(recovery_dec) if recovery_dec else {}

        mttr = round(recovery_t - fault_t, 6)
        trace_fault    = _sl_trace(fault_dec,    fault_result,    now)
        trace_recovery = _sl_trace(recovery_dec, recovery_result, recovery_t)

        return {
            "scenario":              scenario["name"],
            "level":                 scenario["level"],
            "description":           scenario["description"],
            "fault_decision":        trace_fault,
            "recovery_decision":     trace_recovery,
            "fault_correct":         fault_dec["action"]    == scenario["expected_fault_action"],
            "recovery_correct":      recovery_dec["action"] == scenario["expected_recovery_action"],
            "mttr_seconds":          mttr,
        }

    # Standard single-cycle scenario
    store = StateStore(window_seconds=60)
    for ev in scenario["events"]:
        store.record({"container": _CONTAINER, "pid": 1, "time": now, **ev})

    decisions = reconcile(store, shadow=False)
    dec = next((d for d in decisions if d["container"] == _CONTAINER), None)
    if not dec:
        dec = {"container": _CONTAINER, "action": "no_action", "score": 0.0,
               "reason": "no events", "kernel_signals": [], "dag_pattern": "nominal",
               "mode": "real", "timestamp": now}
    result  = execute(dec)
    trace   = _sl_trace(dec, result, now)

    return {
        "scenario":    scenario["name"],
        "level":       scenario["level"],
        "description": scenario["description"],
        "decision":    trace,
        "correct":     dec["action"] == scenario["expected_action"],
    }


def _sl_trace(dec: dict, result: dict, t: float) -> dict:
    return {
        "trace_time":    t,
        "container":     dec.get("container"),
        "score":         dec.get("score"),
        "action":        dec.get("action"),
        "mode":          dec.get("mode", "real"),
        "why":           dec.get("reason", ""),
        "kernel_signals": dec.get("kernel_signals", []),
        "dag_pattern":   dec.get("dag_pattern"),
        "reversibility": result.get("reversibility"),
        "blocked_reason": None,
        "node_type":     "S",
    }


# ── Stateful runner ────────────────────────────────────────────────────────────

def _run_sf_scenario(mods: dict, scenario: dict, now: float) -> dict:
    """Run one stateful scenario. Returns a result dict."""
    StatefulStateStore = mods["state_store"].StatefulStateStore
    ContainerFSM       = mods["fsm"].ContainerFSM
    reconcile          = mods["reconcile"].reconcile
    execute            = mods["actions"].execute

    if scenario.get("level") == "R":
        fsm_fault = ContainerFSM()
        store_fault = StatefulStateStore(window_seconds=60)
        for ev in scenario["fault_events"]:
            store_fault.record({"container": _CONTAINER, "pid": 1,
                                "time": now, "node_type": "F", **ev})
        fault_decisions = reconcile(store_fault, fsm_fault, shadow=False)
        fault_t = time.time()
        fault_dec = next((d for d in fault_decisions if d["container"] == _CONTAINER), None)
        fault_result = execute(fault_dec) if fault_dec else {}

        # Clear window
        fsm_recovery = ContainerFSM()
        store_recovery = StatefulStateStore(window_seconds=60)
        for ev in scenario.get("recovery_events", []):
            store_recovery.record({"container": _CONTAINER, "pid": 1,
                                   "time": now - 70, "node_type": "F", **ev})
        recovery_decisions = reconcile(store_recovery, fsm_recovery, shadow=False)
        recovery_t = time.time()
        recovery_dec = next((d for d in recovery_decisions if d["container"] == _CONTAINER), None)
        if not recovery_dec:
            recovery_dec = {"container": _CONTAINER, "action": "no_action", "score": 0.0,
                            "reason": "no events in window", "kernel_signals": [],
                            "dag_pattern": "nominal", "mode": "real",
                            "fsm_state": "Healthy", "fsm_state_after": "Healthy",
                            "fsm_transition": None, "reversibility": "reversible",
                            "blocked_reason": None, "timestamp": recovery_t}
        recovery_result = execute(recovery_dec)

        mttr = round(recovery_t - fault_t, 6)
        trace_fault    = _sf_trace(fault_dec,    fault_result,    now)
        trace_recovery = _sf_trace(recovery_dec, recovery_result, recovery_t)

        return {
            "scenario":              scenario["name"],
            "level":                 scenario["level"],
            "description":           scenario["description"],
            "fault_decision":        trace_fault,
            "recovery_decision":     trace_recovery,
            "fault_correct":         fault_dec["action"]    == scenario["expected_fault_action"] if fault_dec else False,
            "recovery_correct":      recovery_dec["action"] == scenario["expected_recovery_action"],
            "mttr_seconds":          mttr,
        }

    fsm   = ContainerFSM()
    store = StatefulStateStore(window_seconds=60)
    for ev in scenario["events"]:
        store.record({"container": _CONTAINER, "pid": 1,
                      "time": now, "node_type": "F", **ev})

    decisions = reconcile(store, fsm, shadow=False)
    dec = next((d for d in decisions if d["container"] == _CONTAINER), None)
    if not dec:
        dec = {"container": _CONTAINER, "action": "no_action", "score": 0.0,
               "reason": "no events", "kernel_signals": [], "dag_pattern": "nominal",
               "mode": "real", "fsm_state": "Healthy", "fsm_state_after": "Healthy",
               "fsm_transition": None, "reversibility": "reversible",
               "blocked_reason": None, "timestamp": now}
    result = execute(dec)
    trace  = _sf_trace(dec, result, now)

    return {
        "scenario":    scenario["name"],
        "level":       scenario["level"],
        "description": scenario["description"],
        "decision":    trace,
        "correct":     dec["action"] == scenario["expected_action"],
    }


def _sf_trace(dec: dict, result: dict, t: float) -> dict:
    return {
        "trace_time":    t,
        "container":     dec.get("container"),
        "score":         dec.get("score"),
        "action":        dec.get("action"),
        "mode":          dec.get("mode", "real"),
        "why":           dec.get("reason", ""),
        "kernel_signals": dec.get("kernel_signals", []),
        "dag_pattern":   dec.get("dag_pattern"),
        "reversibility": result.get("reversibility") or dec.get("reversibility"),
        "blocked_reason": dec.get("blocked_reason"),
        "node_type":     "F",
        "fsm_state":     dec.get("fsm_state"),
        "wasm_blocked":  result.get("wasm_blocked", False),
    }


# ── Aggregate metrics over scenario results ────────────────────────────────────

def _aggregate(results: list) -> dict:
    """Compute aggregate metrics over a list of scenario result dicts."""
    all_traces = []
    mttr_samples = []
    correct_count = 0
    total_count = 0

    for r in results:
        if r["level"] == "R":
            all_traces.append(r["fault_decision"])
            all_traces.append(r["recovery_decision"])
            if r.get("fault_correct"):
                correct_count += 1
            if r.get("recovery_correct"):
                correct_count += 1
            total_count += 2
            mttr_samples.append(r["mttr_seconds"])
        else:
            all_traces.append(r["decision"])
            if r.get("correct"):
                correct_count += 1
            total_count += 1

    active = [t for t in all_traces if t.get("action") != "no_action" and t.get("reversibility") is not None]
    reversible = sum(1 for t in active if t.get("reversibility") == "reversible")

    suppressed = sum(
        1 for t in all_traces
        if t.get("wasm_blocked") is True or (t.get("blocked_reason") not in (None, ""))
    )

    complete = sum(1 for t in all_traces if _complete(t))

    return {
        "decision_accuracy":               round(correct_count / total_count, 4) if total_count else 0.0,
        "reversibility_ratio":             round(reversible / len(active), 4) if active else 0.0,
        "explanation_completeness":        round(complete / len(all_traces), 4) if all_traces else 0.0,
        "unsafe_action_suppression_rate":  round(suppressed / len(all_traces), 4) if all_traces else 0.0,
        "mttr_seconds":                    round(sum(mttr_samples) / len(mttr_samples), 6) if mttr_samples else None,
        "n_scenarios":                     len(results),
        "n_decisions":                     len(all_traces),
        "n_correct":                       correct_count,
    }


# ── Main ───────────────────────────────────────────────────────────────────────

def run(out_file: str = OUT_FILE) -> dict:
    now = time.time()

    print("[cross_eval] Loading stateless modules...")
    sl_mods = _load_track("stateless")
    print("[cross_eval] Loading stateful modules...")
    sf_mods = _load_track("stateful")

    print("\n[cross_eval] Running stateless (S) scenarios...")
    sl_results = []
    for sc in S_SCENARIOS:
        r = _run_sl_scenario(sl_mods, sc, now)
        status = "✓" if r.get("correct", r.get("fault_correct", False)) else "✗"
        action = r.get("decision", r.get("fault_decision", {})).get("action", "?")
        print(f"  [{status}] {sc['name']:<22} action={action}")
        sl_results.append(r)

    print("\n[cross_eval] Running stateful (F) scenarios...")
    sf_results = []
    for sc in F_SCENARIOS:
        r = _run_sf_scenario(sf_mods, sc, now)
        status = "✓" if r.get("correct", r.get("fault_correct", False)) else "✗"
        action = r.get("decision", r.get("fault_decision", {})).get("action", "?")
        print(f"  [{status}] {sc['name']:<22} action={action}")
        sf_results.append(r)

    sl_metrics = _aggregate(sl_results)
    sf_metrics = _aggregate(sf_results)

    print("\n[cross_eval] Metrics comparison:")
    print(f"  {'metric':<40} {'stateless':>12} {'stateful':>12}")
    print(f"  {'-'*64}")
    for k in ("decision_accuracy", "reversibility_ratio", "explanation_completeness",
              "unsafe_action_suppression_rate", "mttr_seconds"):
        sv = sl_metrics.get(k)
        fv = sf_metrics.get(k)
        print(f"  {k:<40} {str(sv):>12} {str(fv):>12}")

    result = {
        "generated_at":      time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "methodology": (
            "Both controllers run on domain-appropriate fault scenarios at matched severity "
            "levels (sub-threshold, minor, major/critical, recovery). Fault types differ by "
            "design: S-track uses process_exit/tcp_connect; F-track uses vfs_write_error/"
            "blk_io_latency/volume_mount_lost. Metrics are computed identically for both. "
            "MTTR measures controller decision latency (fault inject → event-clear → "
            "no_action decision), not wall-clock fault duration."
        ),
        "severity_level_mapping": {
            "level_0_sub_threshold": {
                "stateless": "3x tcp_connect → score=0.54",
                "stateful":  "1x vfs_write_error → score=0.293",
            },
            "level_1_minor": {
                "stateless": "5x tcp_connect → score=0.90 → restart",
                "stateful":  "2x vfs_write_error → score=0.587 → flush_io_queue",
            },
            "level_2_major": {
                "stateless": "(no distinct major level; reschedule at level 3)",
                "stateful":  "5x blk_io_latency_high → score=0.85 → flush_io_queue (FSM-gated cycle 1)",
            },
            "level_3_critical": {
                "stateless": "1x process_exit → score=0.95 → reschedule",
                "stateful":  "1x volume_mount_lost → score=0.97 → escalate",
            },
        },
        "stateless": {
            "scenarios": sl_results,
            "metrics":   sl_metrics,
        },
        "stateful": {
            "scenarios": sf_results,
            "metrics":   sf_metrics,
        },
    }

    with open(out_file, "w") as f:
        json.dump(result, f, indent=2)
    print(f"\n[cross_eval] Results written to {out_file}")

    return result


if __name__ == "__main__":
    run()
