_repo = os.path.dirname(_here)

OUT_FILE = os.path.join(_here, "cross_eval_results.json")

# ── Module loader (avoids sys.path contamination between tracks) ───────────────

def _load_track(track: str):
    """
    Load all relevant modules for a track ('stateless' or 'stateful').

    Each track's directory is prepended to sys.path for the duration of loading,
    then removed so the other track's same-named modules (confidence.py, etc.)
    are not found via the wrong path.  The other track's directory is also
    temporarily removed to prevent cross-contamination.
    """
    d       = os.path.join(_repo, track)
    other   = os.path.join(_repo, "stateless" if track == "stateful" else "stateful")

    # Remove the other track dir from path, add ours at front
    saved_path = list(sys.path)
    sys.path = [p for p in sys.path if p != other]
    if d not in sys.path:
        sys.path.insert(0, d)

    mods = {}
    # Load in dependency order: actions before reconcile (reconcile imports from actions)
    load_order = ["state_store", "confidence"]
    if track == "stateful":
        load_order += ["fsm"]
    load_order += ["actions", "reconcile"]

    for name in load_order:
        full_name = f"{track}_{name}"   # unique key in sys.modules
        path      = os.path.join(d, f"{name}.py")
        spec = importlib.util.spec_from_file_location(full_name, path)
        mod  = importlib.util.module_from_spec(spec)
        sys.modules[full_name] = mod    # register before exec so relative imports resolve
        # Also register under the bare name so intra-track imports (e.g. `from confidence import`)
        # resolve to THIS track's version during exec
        sys.modules[name] = mod
        spec.loader.exec_module(mod)
        mods[name] = mod

    # Restore sys.path but keep our track dir (modules may need it at call time)
    sys.path = saved_path
    if d not in sys.path:
        sys.path.insert(0, d)

    return mods


